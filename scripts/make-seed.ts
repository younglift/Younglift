// Generates supabase/seed.sql from the mock data, so the database starts with the prototype makers.
// Run: npx tsx scripts/make-seed.ts
import { writeFileSync } from 'node:fs';
import { MAKERS, MAKER_EXTRAS, PRODUCTS } from '../lib/data/mock-data';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[]) => `array[${a.map(q).join(', ')}]::text[]`;
const json = (o: unknown) => (o === undefined ? 'null' : `${q(JSON.stringify(o))}::jsonb`);
const MONTHS: Record<string, string> = { Aug: '08', Sep: '09', Oct: '10', Nov: '11' };
const date = (s: string) => { const [d, m] = s.split(' '); return `2026-${MONTHS[m]}-${d.padStart(2, '0')}`; };

const out: string[] = ['-- Generated by scripts/make-seed.ts from lib/data/mock-data.ts. Demo makers from the prototype.', 'begin;'];

MAKERS.forEach((m, i) => {
  const { journal: _j, ...extras } = MAKER_EXTRAS[m.id];
  out.push(`insert into public.makers (id, slug, name, studio, city, country, categories, quote, bio, portrait_url, cover_url, style, sections, status, extras, sort) values (${[
    q(m.id), q(m.slug), q(m.name), q(m.studio), q(m.city), q(m.country), arr(m.categories), q(m.quote), q(m.bio),
    q(m.portraitUrl), q(m.coverUrl), q(m.style), arr(m.sections), q('approved'), json(extras), i,
  ].join(', ')}) on conflict (id) do nothing;`);
});

PRODUCTS.forEach((p, i) => {
  out.push(`insert into public.products (id, maker_id, title, description, price_cents, images, category, materials, variants, stock, one_of_a_kind, shipping_cents, sort) values (${[
    q(p.id), q(p.makerId), q(p.title), q(p.description), p.priceCents, arr(p.images), q(p.category), arr(p.materials),
    json(p.variants), p.stock, p.oneOfAKind, p.shippingCents, i,
  ].join(', ')}) on conflict (id) do nothing;`);
});

for (const m of MAKERS) {
  const x = MAKER_EXTRAS[m.id];
  const closer = PRODUCTS.find((p) => p.id === x.closerProductId);
  const media = [...x.work, x.meet.image, x.process.image, ...(closer ? [closer.images[0]] : [])];
  media.forEach((url, i) => out.push(`insert into public.media (maker_id, type, url, sort) values (${q(m.id)}, 'image', ${q(url)}, ${i});`));
  x.journal.forEach((j) => out.push(`insert into public.posts (maker_id, title, body, image_url, is_video, published_at) values (${[
    q(m.id), q(j.title), q(j.text), q(j.image ?? null), Boolean(j.isVideo), q(date(j.date)),
  ].join(', ')});`));
}

out.push('commit;', '');
writeFileSync('supabase/seed.sql', out.join('\n'));
console.log(`seed.sql: ${MAKERS.length} makers, ${PRODUCTS.length} products`);
